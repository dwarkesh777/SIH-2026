// Pre-sort dictionary keys by length descending to ensure specific terms match before generic ones
const SORTED_CROP_KEYS = Object.keys(CROP_TRANSLATIONS).sort((a, b) => b.length - a.length);

/**
 * Translates any crop name (Gujarati or variations) to standardized clean English.
 */
export const getLocalizedCropName = (cropName) => {
    if (!cropName) return '';
    const clean = String(cropName).trim();
    const lowerKey = clean.toLowerCase();

    // 1. Exact match
    if (CROP_TRANSLATIONS[lowerKey]) return CROP_TRANSLATIONS[lowerKey];
    if (CROP_TRANSLATIONS[clean]) return CROP_TRANSLATIONS[clean];

    // 2. Substring match (longest key first)
    for (const gKey of SORTED_CROP_KEYS) {
        if (lowerKey.includes(gKey.toLowerCase()) || clean.includes(gKey)) {
            return CROP_TRANSLATIONS[gKey];
        }
    }

    // Capitalize if it's an unmapped English string
    if (/^[a-zA-Z\s]+$/.test(clean)) {
        return clean.split(' ').map(w => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase()).join(' ');
    }

    return clean;
};

// Alias for convenience
export const localizeCropName = getLocalizedCropName;

/**
 * Translates Gujarati market/mandi names to clean English APMC titles.
 */
export const getLocalizedMarketName = (marketName) => {
    if (!marketName) return 'APMC Yard';
    let engName = String(marketName).trim();
    if (engName.includes('માર્કેટ યાર્ડ')) engName = engName.replace('માર્કેટ યાર્ડ', 'APMC');
    if (engName.includes('જૂનાગઢ')) engName = engName.replace('જૂનાગઢ', 'Junagadh');
    if (engName.includes('રાજકોટ')) engName = engName.replace('રાજકોટ', 'Rajkot');
    if (engName.includes('ગોંડલ')) engName = engName.replace('ગોંડલ', 'Gondal');
    if (engName.includes('જેતપુર')) engName = engName.replace('જેતપુર', 'Jetpur');
    if (engName.includes('જામનગર')) engName = engName.replace('જામનગર', 'Jamnagar');
    if (engName.includes('અમરેલી')) engName = engName.replace('અમરેલી', 'Amreli');
    if (engName.includes('મોરબી')) engName = engName.replace('મોરબી', 'Morbi');
    if (engName.includes('ભાવનગર')) engName = engName.replace('ભાવનગર', 'Bhavnagar');
    if (engName.includes('સુરત')) engName = engName.replace('સુરત', 'Surat');
    if (engName.includes('અમદાવાદ')) engName = engName.replace('અમદાવાદ', 'Ahmedabad');
    if (engName.includes('વડોદરા')) engName = engName.replace('વડોદરા', 'Vadodara');

    const lower = engName.toLowerCase();
    if (lower === 'junagadh' || lower === 'junagadh apmc' || lower === 'junagadh market yard') return 'Junagadh APMC';
    if (lower === 'rajkot' || lower === 'rajkot apmc' || lower === 'rajkot market yard') return 'Rajkot APMC';
    if (lower === 'gondal' || lower === 'gondal apmc' || lower === 'gondal market yard') return 'Gondal APMC';
    if (lower === 'jetpur' || lower === 'jetpur apmc' || lower === 'jetpur market yard') return 'Jetpur APMC';
    return engName;
};

/**
 * Converts any Gujarati numerals to English digits
 */
export const toEnglishDigits = (str) => {
    if (!str) return '';
    const gujDigitsMap = {
        '૦': '0', '૧': '1', '૨': '2', '૩': '3', '૪': '4',
        '૫': '5', '૬': '6', '૭': '7', '૮': '8', '૯': '9'
    };
    return String(str).replace(/[૦-૯]/g, d => gujDigitsMap[d] || d);
};
